<?php
/**
 * Generates connector/compat-1x.php, the connector 1.x names (cm_ / CM_) that hosts built before 2.0.0 call,
 * from docs/connector-prefix-map.json and the connector's own source.
 *
 * Run: php bin/connector-compat.php            write connector/compat-1x.php
 *      php bin/connector-compat.php --check    exit 1 if connector/compat-1x.php is not what this would write
 *      (optional trailing arguments: <map.json> <connector-dir> <out.php>, for the tests)
 *
 * Fails when a mapped function no longer exists under its new name, or takes or returns a reference and has no
 * hand-written wrapper below (a variadic forwarder would drop the reference).
 *
 * @package MonksCentral
 */

$wpshq_root  = dirname( __DIR__ );
$wpshq_args  = array_values( array_diff( array_slice( $argv, 1 ), array( '--check' ) ) );
$wpshq_check = in_array( '--check', $argv, true );
$wpshq_map   = $wpshq_args[0] ?? $wpshq_root . '/docs/connector-prefix-map.json';
$wpshq_dir   = $wpshq_args[1] ?? $wpshq_root . '/connector';
$wpshq_out   = $wpshq_args[2] ?? $wpshq_dir . '/compat-1x.php';

// Forwarders for functions with a by-reference parameter, keyed by the old name.
const WPSHQ_COMPAT_BY_REF = array(
	'cm_acf_collect_refs'    => "function cm_acf_collect_refs( array \$field, \$value, array &\$ids ) { // %s\n\t\treturn wpshq_acf_collect_refs( \$field, \$value, \$ids );\n\t}",
	'cm_content_post_fields' => "function cm_content_post_fields( \$post_type, \$post_id, \$input, array &\$post_data ) { // %s\n\t\treturn wpshq_content_post_fields( \$post_type, \$post_id, \$input, \$post_data );\n\t}",
);

const WPSHQ_COMPAT_IGNORE = 'phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.%s -- 1.x name, see the file comment.';

/**
 * Functions declared in the connector's PHP files: name => array( takes or returns a reference, returns void ).
 *
 * @param string $dir Connector folder.
 * @return array<string, bool[]>
 */
function wpshq_compat_declared( $dir ) {
	$found = array();
	$files = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ) );
	foreach ( $files as $file ) {
		if ( 'php' !== $file->getExtension() || str_contains( substr( $file->getPathname(), strlen( $dir ) ), '/tests/' ) || 'compat-1x.php' === $file->getFilename() ) {
			continue;
		}
		$tokens = token_get_all( file_get_contents( $file->getPathname() ) );
		$count  = count( $tokens );
		for ( $i = 0; $i < $count; $i++ ) {
			if ( ! is_array( $tokens[ $i ] ) || T_FUNCTION !== $tokens[ $i ][0] ) {
				continue;
			}
			$by_ref = false;
			$name   = null;
			for ( $depth = 0, $j = $i + 1; $j < $count; $j++ ) { // Name, then the parameter list; & anywhere is a reference.
				$t      = $tokens[ $j ];
				$by_ref = $by_ref || '&' === $t || ( is_array( $t ) && in_array( $t[0], array( T_AMPERSAND_FOLLOWED_BY_VAR_OR_VARARG, T_AMPERSAND_NOT_FOLLOWED_BY_VAR_OR_VARARG ), true ) );
				$name   = 0 === $depth && is_array( $t ) && T_STRING === $t[0] ? $t[1] : $name;
				$depth += '(' === $t ? 1 : ( ')' === $t ? -1 : 0 );
				if ( ')' === $t && 0 === $depth ) {
					break;
				}
			}
			$doc  = $tokens[ $i - 2 ] ?? null; // Docblock, newline, function.
			$tail = '';
			for ( $k = $j + 1; $k < $count && '{' !== $tokens[ $k ] && ';' !== $tokens[ $k ]; $k++ ) {
				$tail .= is_array( $tokens[ $k ] ) ? $tokens[ $k ][1] : $tokens[ $k ];
			}
			$void = 'void' === trim( $tail, " \t\n:" ) || ( is_array( $doc ) && T_DOC_COMMENT === $doc[0] && preg_match( '/@return\s+void\b/', $doc[1] ) );
			if ( null !== $name ) {
				$found[ $name ] = array( $by_ref, $void );
			}
		}
	}
	return $found;
}

/**
 * The hooks the connector fires as actions (the rest of the map's hooks are filters).
 *
 * @param string $dir Connector folder.
 * @return string[]
 */
function wpshq_compat_actions( $dir ) {
	$src = '';
	foreach ( new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ) ) as $file ) {
		$src .= 'php' === $file->getExtension() ? file_get_contents( $file->getPathname() ) : '';
	}
	preg_match_all( "/do_action(?:_ref_array)?\(\s*'(wpshq_\w+)'/", $src, $m );
	return array_unique( $m[1] );
}

/**
 * The text of compat-1x.php.
 *
 * @param array  $map Prefix map.
 * @param string $dir Connector folder.
 * @return string
 */
function wpshq_compat_render( array $map, $dir ) {
	$declared = wpshq_compat_declared( $dir );
	$actions  = wpshq_compat_actions( $dir );
	$errors   = array();
	$out      = <<<'PHP'
<?php
/**
 * Connector 1.x names, for host plugins built before connector 2.0.0.
 *
 * GENERATED by bin/connector-compat.php from docs/connector-prefix-map.json. Do not edit; change the generator and
 * run `php bin/connector-compat.php` (`--check` verifies this file is current).
 *
 * Connector 2.0.0 renamed every connector symbol from cm_ / CM_ to wpshq_ / WPSHQ_. Plugins that still bundle a 1.x
 * copy (Classic Monks Pro releases before its 2.0.0 sync) call this library by the old names, and the version-wins
 * loader runs this 2.x copy instead of theirs, so those calls would fatal. Monks_Central_Connector::boot() requires
 * this file only while such a copy is registered. It gives the old names back as thin forwarders to the new ones:
 * class aliases, constants, functions, and the old hook names fired next to the new ones.
 *
 * The cm_ / CM_ names below are not new globals: they are the published 1.x API of this same library, kept so sites
 * do not break while their host plugin updates. Each declaration is skipped when the name already exists or its new
 * name is not loaded, and carries a per-line PrefixAllGlobals ignore. Remove this file once no supported host
 * bundles a 1.x connector.
 *
 * @package MonksCentral\Connector
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

// 1.x hosts call the media helpers by name after requiring this file from the running copy; they load lazily in 2.x.
require_once __DIR__ . '/media-import-helpers.php';

PHP;

	foreach ( $map['classes'] as $old => $new ) {
		$out .= "\nif ( class_exists( '$new', false ) && ! class_exists( '$old', false ) ) {\n\tclass_alias( '$new', '$old' );\n}\n";
	}
	foreach ( $map['constants'] as $old => $new ) {
		$out .= "\nif ( defined( '$new' ) && ! defined( '$old' ) ) {\n\tdefine( '$old', $new ); // " . sprintf( WPSHQ_COMPAT_IGNORE, 'NonPrefixedConstantFound' ) . "\n}\n";
	}
	foreach ( $map['functions'] as $old => $new ) {
		if ( ! isset( $declared[ $new ] ) ) {
			$errors[] = "$new (for $old) is not declared under the connector folder";
			continue;
		}
		$ignore = sprintf( WPSHQ_COMPAT_IGNORE, 'NonPrefixedFunctionFound' );
		if ( isset( WPSHQ_COMPAT_BY_REF[ $old ] ) ) {
			$body = sprintf( WPSHQ_COMPAT_BY_REF[ $old ], $ignore );
		} elseif ( $declared[ $new ][0] ) {
			$errors[] = "$new takes or returns a reference: add a wrapper for $old to WPSHQ_COMPAT_BY_REF";
			continue;
		} else {
			$call = $declared[ $new ][1] ? '' : 'return ';
			$body = "function $old( ...\$args ) { // $ignore\n\t\t$call$new( ...\$args );\n\t}";
		}
		$out .= "\nif ( function_exists( '$new' ) && ! function_exists( '$old' ) ) {\n\t$body\n}\n";
	}
	foreach ( $map['hooks'] as $old => $new ) {
		$action = in_array( $new, $actions, true );
		$add    = $action ? 'add_action' : 'add_filter';
		$fire   = $action ? "do_action( '$old', ...\$args );" : "return apply_filters( '$old', ...\$args );";
		$out   .= "\n$add(\n\t'$new',\n\tstatic function ( ...\$args ) {\n\t\t$fire // " . sprintf( WPSHQ_COMPAT_IGNORE, 'NonPrefixedHooknameFound' ) . "\n\t},\n\t10,\n\t9\n);\n";
	}
	if ( $errors ) {
		fwrite( STDERR, implode( "\n", $errors ) . "\n" );
		exit( 2 );
	}
	return $out;
}

$wpshq_text = wpshq_compat_render( json_decode( file_get_contents( $wpshq_map ), true ), $wpshq_dir );
if ( $wpshq_check ) {
	$wpshq_ok = is_readable( $wpshq_out ) && file_get_contents( $wpshq_out ) === $wpshq_text;
	echo $wpshq_ok ? "$wpshq_out is current\n" : "$wpshq_out is out of date: run php bin/connector-compat.php\n";
	exit( $wpshq_ok ? 0 : 1 );
}
file_put_contents( $wpshq_out, $wpshq_text );
echo "wrote $wpshq_out\n";
